def normalize_locale(value):
    if value in SUPPORTED_LOCALES:
        return value
    language = (value or "")[:2].lower()
    return next((locale for locale in SUPPORTED_LOCALES if locale[:2].lower() == language), "en-US")


def get_locale():
    if current_user.is_authenticated and current_user.locale:
        return normalize_locale(current_user.locale)
    if session.get("locale"):
        return normalize_locale(session["locale"])
    return normalize_locale(request.accept_languages.best_match(SUPPORTED_LOCALES))


def translate(text):
    return TRANSLATIONS.get(get_locale(), {}).get(text, text)
